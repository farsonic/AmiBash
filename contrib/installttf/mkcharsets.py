#!/usr/bin/env python3
"""mkcharsets.py - write charsets.h: the upper half of each character set
InstallTTF offers, as Unicode, for the code page in the .otag file."""
sets = [('latin1', 'iso8859_1'), ('latin2', 'iso8859_2'), ('latin3', 'iso8859_3'), ('latin4', 'iso8859_4'),
        ('latin5', 'iso8859_9'), ('latin9', 'iso8859_15'), ('latin10', 'iso8859_16'), ('cp1250', 'cp1250'),
        ('cyrillic', 'iso8859_5'), ('koi8r', 'koi8_r')]
out = ['/* charsets.h - generated by mkcharsets.py: the upper half (0x80-0xFF) of each\n'
       ' * character set as Unicode, for the .otag code page */\n',
       'static const struct { const char *name; UWORD hi[128]; } charsets[] = {']
for n, c in sets:
    vals = []
    for b in range(0x80, 0x100):
        try:
            vals.append(ord(bytes([b]).decode(c)))
        except UnicodeDecodeError:
            vals.append(b)
    rows = ',\n        '.join(', '.join('0x%04X' % v for v in vals[i:i + 8]) for i in range(0, 128, 8))
    out.append('    {"%s", {\n        %s}},' % (n, rows))
out.append('};\n#define NCHARSETS (sizeof(charsets) / sizeof(charsets[0]))\n')
open('charsets.h', 'w').write('\n'.join(out))
