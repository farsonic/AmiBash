# run.sh - compare the AmiBash built-in utilities (via the test driver)
# with GNU coreutils/grep/sed on the host.
#
# Each case is a shell command in which utilities are written as "$U name";
# it is run once with U empty (GNU) and once with U=driver, each in a fresh
# copy of the fixture directory.  stdout and the exit status are compared
# (stderr is ignored since messages are prefixed "bash: " in AmiBash).
#
#   tests/utils/run.sh [-v] [FILTER]

