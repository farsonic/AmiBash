    printf 'name,age,city\nalice,30,paris\nbob,25,london\ncarol,35,berlin\ndave,25,paris\n' > people.csv
    printf 'root:x:0:0:root:/root:/bin/bash\ndaemon:x:1:1:daemon:/usr/sbin:/usr/sbin/nologin\nuser:x:1000:1000:User Name:/home/user:/bin/sh\n' > passwd
    printf 'the quick brown fox\njumps over the lazy dog\nThe End\n\nfoo bar foo\nfoobar\nbarfoo baz\n' > text.txt
    printf 'a\na\nb\nc\nc\nc\nA\na\nd\n' > dup.txt
    printf 'line1\nline2\nline3\nline4\nline5\nline6\nline7\nline8\nline9\nline10\nline11\nline12\n' > lines.txt
    printf 'no newline at end' > nonl.txt
    printf '' > empty.txt
    printf 'x\ty\tz\n1\t2\t3\n\tlead\n' > tabs.txt
    printf '  3 c\n 1 a\n2 b\n10 j\n' > lead.txt
    printf '1.5K\n2M\n100\n1G\n3K\n512\n' > human.txt
    printf 'Mar 3\nJan 1\nDec 9\nfeb 2\nxyz 0\n' > months.txt
    printf 'file-1.10\nfile-1.2\nfile-1.9\nfile-10\nfile-2\n' > vers.txt
    mkdir -p d1/sub1 d1/sub2/deep d2
    printf 'hello\n' > d1/a.txt
    printf 'world\nhello again\n' > d1/sub1/b.txt
    printf 'deep file\n' > d1/sub2/deep/c.dat
    printf 'x\n' > d1/sub2/e.txt
    printf '1234567890' > d2/ten
    : > d2/zero
    touch -d '2020-01-01 00:00:00' d1/a.txt
    touch -d '2024-06-01 12:00:00' d1/sub1/b.txt
}

t() {
    local cmd=$1 exp got
    [ -n "$FILTER" ] && [[ "$cmd" != *$FILTER* ]] && return
    mkfix "$TMP/gnu"
    exp=$(U=; eval "$cmd" 2>/dev/null; echo "[rc=$?]")
    mkfix "$TMP/ami"
    got=$(U=$D; eval "$cmd" 2>/dev/null; echo "[rc=$?]")
    cd "$TMP"
    if [ "$exp" == "$got" ]; then
        pass=$((pass + 1))
        [ $VERBOSE = 1 ] && echo "ok   $cmd"
    else
        fail=$((fail + 1))
        failed+=("$cmd")
        echo "FAIL $cmd"
        diff <(echo "$exp") <(echo "$got") | head -20 | sed 's/^/     /'
    fi
}

